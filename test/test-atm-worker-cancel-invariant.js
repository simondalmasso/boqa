const assert=require('assert'),fs=require('fs'),path=require('path');
const {fixtureRepo,makeJob,tmpRun,sh}=require('./atm-worker-test-helpers');
const {computeScopeHash}=require('../atm-worker/contract/canonicalize');
const {cancelRun}=require('../atm-worker/runtime/cancel');
const runnerPath=require.resolve('../atm-worker/runtime/process-runner');
const workerPath=require.resolve('../atm-worker/worker');
const realRunner=require(runnerPath);

const repo=fixtureRepo(),root=tmpRun();
let calls=0;
require.cache[runnerPath].exports={...realRunner,runDocker(){calls++;const c=cancelRun(root);assert.equal(c.status,'CANCELLED');return {status:0,timedOut:false,stdout:'valid pre-check returned after cancellation',stderr:''};}};
delete require.cache[workerPath];
const {runJob}=require(workerPath);
const job=makeJob(repo,{job_id:'cancel-valid-precheck-no-expect',required_capabilities:['SMALL_BOUNDED_CODE_FIX','EVIDENCE_GENERATION'],structured_requirements:{lease_status:'active',pre_checks:[{executable:'node',args:['-e','process.exit(0)']}],post_checks:[],edit_recipe:{type:'exact_replace',path:'allowed.txt',before:'before\n',after:'after\n'}},runtime_profile:{snapshot_path:repo.dir,image:'node:20-bookworm-slim',allowed_executables:['node'],hydration_commands:[]}});
job.scope_hash=computeScopeHash(job);
const result=runJob(job,root);
assert.equal(calls,1);
assert.equal(result.status,'CANCELLED');
assert.equal(result.error_class,'CANCELLED');
assert.equal(result.patch_sha256,null);
assert.equal(result.local_commit_sha,null);
assert.deepEqual(result.changed_paths,[]);
assert.equal(fs.readFileSync(path.join(root,'target','allowed.txt'),'utf8'),'before\n');
assert.equal(sh('git',['rev-parse','HEAD'],path.join(root,'target')),job.target_base_sha);
assert.equal(sh('git',['status','--porcelain'],path.join(root,'target')),'');
assert(!fs.existsSync(path.join(root,'artifacts','bounded.patch')));
const ledger=fs.readFileSync(path.join(root,'receipts.jsonl'),'utf8');
assert(!ledger.includes('RESULT_READY'));
assert(!ledger.includes('"status":"COMPLETED"'));
assert.deepEqual(runJob(job,root),result,'terminal cancellation result must remain idempotent');
require.cache[runnerPath].exports=realRunner;
delete require.cache[workerPath];
console.log('ATM worker cancellation dominates valid pre-check without expect_status: PASS');
